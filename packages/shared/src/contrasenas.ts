/** Contraseñas comunes, en minúsculas y NFC. Exportada para las pruebas. */
export const CONTRASENAS_COMUNES: ReadonlySet<string> = new Set(LISTA.map(normalizarContrasena));

function normalizarContrasena(valor: string): string {
  return valor.normalize('NFC').toLowerCase();
}

/** `true` si la contraseña está en la lista de comunes (sin distinguir mayúsculas). */
export function esContrasenaComun(valor: string): boolean {
  return CONTRASENAS_COMUNES.has(normalizarContrasena(valor));
}

/** `true` si toda la contraseña es un mismo carácter repetido (sin distinguir mayúsculas). */
export function esCaracterRepetido(valor: string): boolean {
  return /^(.)\1+$/su.test(normalizarContrasena(valor));
}
